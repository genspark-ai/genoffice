/**
 * Every Docs command, whichever of the menu bar and the ribbon offers it: its
 * menu label key and accelerator live here once. A command without a menu key
 * has no menu item yet.
 */
export interface CommandDef {
  /** key into the main-process menu dictionary */
  menuKey?: string
  accelerator?: string | { mac: string; other: string }
  /** shown with a check mark that follows the renderer's state */
  toggle?: true
  /** Word has it and it is not built yet: listed in Word's place, shown nowhere */
  planned?: true
  /** carried out natively by the focused text target, never sent to the renderer */
  role?: 'cut' | 'copy' | 'paste' | 'pasteAndMatchStyle' | 'selectAll'
}

