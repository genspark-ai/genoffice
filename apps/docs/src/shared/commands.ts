export type CommandId = keyof typeof COMMANDS

/** a payload that names "no value": no highlight, the automatic colour, no shading, no wrapping */
export const NONE = 'none'

/** commands the menu carries out itself through a native role */
export type RoleCommandId = {
  [K in CommandId]: (typeof COMMANDS)[K] extends { role: string } ? K : never
}[CommandId]

export function isPlanned(id: string): boolean {
  return Object.hasOwn(COMMANDS, id) && !!(COMMANDS as Record<string, CommandDef>)[id]!.planned
}

/** commands that are not built yet */
export type PlannedCommandId = {
  [K in CommandId]: (typeof COMMANDS)[K] extends { planned: true } ? K : never
}[CommandId]

/** commands sent to the renderer to run */
export type ActionCommandId = Exclude<CommandId, RoleCommandId | PlannedCommandId>

/** what the renderer tells the menu bar about its commands: which are checked, which unavailable */
export interface CommandMenuState {
  checked: CommandId[]
  disabled: CommandId[]
  /** what Edit > Repeat would do, which is also its label; absent when nothing */
  repeat?: RepeatMode
}

export type RepeatMode = 'redo' | 'repeat'

/** keeps only real command ids from a value that crossed the IPC boundary */
export function toCommandMenuState(value: unknown): CommandMenuState {
  const ids = (list: unknown): CommandId[] =>
    Array.isArray(list)
      ? list.filter((id): id is CommandId => typeof id === 'string' && Object.hasOwn(COMMANDS, id))
      : []
  const state = value as { checked?: unknown; disabled?: unknown; repeat?: unknown } | null
  const repeat = state?.repeat
  return {
    checked: ids(state?.checked),
    disabled: ids(state?.disabled),
    ...(repeat === 'redo' || repeat === 'repeat' ? { repeat } : {}),
  }
}
