import type { Lang } from '@genoffice/i18n'

/**
 * The command palette's own labels (Ctrl/Cmd+K launcher). Kept separate from
 * the shell's big lazily-loaded dictionaries: the palette is small, mounts on
 * demand, and ships one static map like the composer's skill labels
 * (`packages/ui/src/strings-ai-skills.ts`).
 *
 * Command hints double as search keywords: they carry the app name and file
 * extension in every language, so typing "sheet" or the localized word for it
 * both find the spreadsheet action.
 */
export interface CommandPaletteStrings {
  /** the overlay's accessible name */
  inputLabel: string
  /** the results list's accessible name */
  resultsLabel: string
  placeholder: string
  /** list body when the query matches nothing */
  empty: string
  /** footer line: how to drive the palette */
  kbdHint: string
  groupCreate: string
  groupRecent: string
  groupSkills: string
  groupSettings: string
  groupPlugins: string
  cmdNewDoc: string
  hintNewDoc: string
  cmdNewSheet: string
  hintNewSheet: string
  cmdNewSlide: string
  hintNewSlide: string
  cmdNewMarkdown: string
  hintNewMarkdown: string
  cmdNewHtml: string
  hintNewHtml: string
  cmdNewPdf: string
  hintNewPdf: string
  cmdBrowse: string
  hintBrowse: string
  setAiModel: string
  hintAiModel: string
  setSkills: string
  hintSkills: string
  /** the chip on an enabled plugin's row: what Enter does */
  pluginDisable: string
  /** the chip on a disabled plugin's row: what Enter does */
  pluginEnable: string
  /** recent row detail when the file failed to stat */
  missingFile: string
}

