  appSheets: string
  appSlides: string
  appPdf: string
  appMarkdown: string
  appHtml: string
  /** the utility tiles */
  appAsk: string
  appTemplates: string
  appPlugins: string
  appSettings: string
  /** the icon region's accessible name */
  desktopAria: string
  /** icon context-menu actions */
  menuOpen: string
  menuReveal: string
  menuReset: string
  /** 从桌面移除: drop a dragged-in alias (the file on disk is untouched) */
  menuRemove: string
  /** empty-surface context menu: the three submenus and the direct actions */
  menuNew: string
  menuSort: string
  menuView: string
  menuRefresh: string
  menuWallpaper: string
  menuProps: string
  /** 排序方式 / Sort-by submenu */
  sortCustom: string
  sortName: string
  sortKind: string
  sortMtime: string
  /** 查看 / View submenu */
  iconSizeLabel: string
  sizeSm: string
  sizeMd: string
  sizeLg: string
  /** icon properties dialog rows */
  propsName: string
  propsType: string
  propsSize: string
  propsModified: string
  propsPath: string
  /** the type shown for a folder icon (files show the uppercased extension) */
  propsFolderType: string
  /** desktop properties dialog rows */
  dpFiles: string
  dpFolders: string
  dpSaveDir: string
  dpOpenSettings: string
  /** wallpaper center */
  wpClose: string
  wpAnimated: string
  wpStatic: string
  wpCustom: string
  wpCustomHint: string
  wpCarousel: string
  carouselOff: string
  carousel1m: string
  carousel10m: string
  carousel30m: string
  carousel1h: string
  /** 填充方式 / wallpaper fit row (image wallpapers only) */
  wpFit: string
  fitCover: string
  fitContain: string
  fitStretch: string
  fitTile: string
  fitCenter: string
  /** 文字颜色 / desktop label color row */
  wpLabelColor: string
  /** the '' preset: follow the theme */
  labelAuto: string
  labelWhite: string
  labelDark: string
  /** the four brand hues (logo.svg) as label colors */
  labelBlue: string
  labelGreen: string
  labelOrange: string
  labelRed: string
  /** the native color picker chip */
