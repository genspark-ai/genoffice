#!/usr/bin/env node
/**
 * Coverage table of the Word layout truths that have an executable fixture.
 *
 * Reads the Word-truths reference (a Markdown file kept outside the repository,
 * one `## ` section per probe wave) and every
 * packages/docx-engine/tests/fixtures/truths/<id>/truth.json, then prints a Markdown
 * table: one row per truths section with the fixture ids that cite it through
 * `"section": "word-truths.md#L<line>"`. Lines are the section heading's line
 * number in the reference file; a fixture citing a bullet inside a section counts
 * for that section.
 *
 *   node tools/truths-coverage.mjs --truths <path/to/word-truths.md> [--out docs/word-truths-coverage.md]
 *
 * Headings are reproduced ASCII-only (non-ASCII runs collapse to one space) so
 * the generated file carries no locale text; fixtures provide an English title.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import prettier from 'prettier'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const FIXTURES = join(ROOT, 'packages/docx-engine/tests/fixtures/truths')

const args = process.argv.slice(2)
const opt = (name) => {
  const i = args.indexOf(name)
  return i === -1 ? undefined : args[i + 1]
}
const truthsPath = opt('--truths') ?? process.env.WORD_TRUTHS_MD
const outPath = opt('--out')
if (!truthsPath || !existsSync(truthsPath)) {
  console.error('usage: node tools/truths-coverage.mjs --truths <word-truths.md> [--out <file.md>]')
  process.exit(2)
}

const lines = readFileSync(truthsPath, 'utf8').split('\n')
const sections = []
for (let i = 0; i < lines.length; i++) {
  if (!lines[i].startsWith('## ')) continue
  if (sections.length) sections[sections.length - 1].end = i
  sections.push({ line: i + 1, heading: lines[i].slice(3), end: lines.length, fixtures: [] })
}
const bulletCount = (s) => lines.slice(s.line, s.end).filter((l) => /^\s*- /.test(l)).length

const fixtures = readdirSync(FIXTURES, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(FIXTURES, d.name, 'truth.json')))
  .map((d) => JSON.parse(readFileSync(join(FIXTURES, d.name, 'truth.json'), 'utf8')))
  .sort((a, b) => a.id.localeCompare(b.id))

const unresolved = []
for (const f of fixtures) {
  const m = /#L(\d+)/.exec(f.section ?? '')
  const line = m ? Number(m[1]) : NaN
  const s = [...sections].reverse().find((x) => x.line <= line)
  if (!s) unresolved.push(f.id)
  else s.fixtures.push(f)
}

const ascii = (s) =>
  s
    .replace(/[^\x20-\x7e]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
/** heading without the parenthesised probe provenance (paths, tool names); a
 *  fixture's section_title wins for headings that are not English */
const title = (s) => {
  const own = s.fixtures.find((f) => f.section_title)?.section_title
  if (own) return own
  const cut = s.heading.search(/[(\uff08]/)
  const head = cut > 0 ? s.heading.slice(0, cut) : s.heading
  const base = ascii(head.replace(/(^|\s)[~/]\S*/g, ' ')).replace(/[\s,:;-]+$/, '')
  const abridged = /[^\x20-\x7e]/.test(head) ? ' (heading abridged)' : ''
  return (base || `section at line ${s.line}`) + abridged
}

const covered = sections.filter((s) => s.fixtures.length)
const totalCases = fixtures.reduce((n, f) => n + f.cases.length, 0)
/** probed Word values the current code does not reproduce (skipped by the runners) */
const failing = fixtures.flatMap((f) =>
  f.cases
    .filter((c) => f.status === 'failing' || c.status === 'failing')
    .map((c) => ({ id: f.id, section: f.section, note: c.note ?? c.kind })),
)
const totalBullets = sections.reduce((n, s) => n + bulletCount(s), 0)
const coveredBullets = covered.reduce((n, s) => n + bulletCount(s), 0)

const out = []
out.push('# Word truths coverage')
out.push('')
out.push(
  'Generated by `node tools/truths-coverage.mjs`; do not edit by hand. A truth is _executable_ when a fixture under `packages/docx-engine/tests/fixtures/truths/` cites its section: pure fixtures run in `apps/docs/tests/truths.test.ts`, render fixtures in `e2e/docs-truths.spec.ts`.',
)
out.push('')
out.push(
  `Sections: **${covered.length} / ${sections.length}** covered (${totalBullets} recorded truths, ${coveredBullets} in covered sections). Fixtures: **${fixtures.length}** (${fixtures.filter((f) => f.class === 'pure').length} pure, ${fixtures.filter((f) => f.class === 'render').length} render) with ${totalCases} cases, ${failing.length} marked failing (bug backlog below).`,
)
out.push('')
out.push('## Covered sections')
out.push('')
out.push('| Line | Section | Truths | Fixtures |')
out.push('|---|---|---|---|')
for (const s of covered) {
  const ids = s.fixtures.map((f) => `\`${f.id}\` (${f.class}, ${f.cases.length})`).join(', ')
  out.push(`| L${s.line} | ${title(s)} | ${bulletCount(s)} | ${ids} |`)
}
out.push('')
out.push('## Fixtures')
out.push('')
out.push('| Fixture | Class | Section | Probe date | Title |')
out.push('|---|---|---|---|---|')
for (const f of fixtures) {
  out.push(`| \`${f.id}\` | ${f.class} | ${f.section} | ${f.probe_date} | ${f.title} |`)
}
out.push('')
if (failing.length) {
  out.push('## Failing cases (bug backlog)')
  out.push('')
  out.push(
    'Word values the fixtures record but the current code does not reproduce; the runners skip them until fixed.',
  )
  out.push('')
  out.push('| Fixture | Section | Case |')
  out.push('|---|---|---|')
  for (const f of failing)
    out.push(`| \`${f.id}\` | ${f.section} | ${f.note.replace(/\|/g, '\\|')} |`)
  out.push('')
}
out.push('## Uncovered sections')
out.push('')
out.push('| Line | Section | Truths |')
out.push('|---|---|---|')
for (const s of sections.filter((x) => !x.fixtures.length)) {
  out.push(`| L${s.line} | ${title(s)} | ${bulletCount(s)} |`)
}
out.push('')
if (unresolved.length) out.push(`Fixtures with no resolvable section: ${unresolved.join(', ')}`)

const target = resolve(ROOT, outPath ?? 'docs/word-truths-coverage.md')
const text = await prettier.format(out.join('\n'), {
  ...(await prettier.resolveConfig(target)),
  parser: 'markdown',
})
if (outPath) {
  writeFileSync(target, text)
  console.log(
    `${covered.length}/${sections.length} sections covered by ${fixtures.length} fixtures -> ${outPath}`,
  )
} else {
  process.stdout.write(text)
}
