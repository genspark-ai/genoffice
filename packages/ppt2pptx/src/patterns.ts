const PCT_PRESETS = Object.keys(PRESET_MASKS).filter((name) => name.startsWith('pct'))

const isBlack = (bytes: Uint8Array, at: number): boolean =>
  bytes[at] === 0 && bytes[at + 1] === 0 && bytes[at + 2] === 0

/**
 * The foreground mask of a pattern blip: an 8×8 1-bpp DIB whose black pixels take
 * the back colour and whose other pixels take the fill colour (as LibreOffice reads it).
 */
export function patternMaskOf(media: PictureMedia): number[] | null {
  if (media.mediaType !== 'image/bmp' || media.bytes.length < 62) return null
  const bytes = media.bytes
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength)
  const width = view.getInt32(18, true)
  const height = view.getInt32(22, true)
  if (width !== 8 || Math.abs(height) !== 8 || view.getUint16(28, true) !== 1) return null
  const offset = view.getUint32(10, true)
  if (offset + 32 > bytes.length) return null
  const setIsForeground = !isBlack(bytes, 58)
  const rows: number[] = []
  for (let y = 0; y < 8; y++) {
    const stored = height > 0 ? 7 - y : y
    const byte = bytes[offset + stored * 4]!
    rows.push(setIsForeground ? byte : ~byte & 0xff)
  }
  return rows
}

/**
 * The DIB's own two colours as fg/bg for the mask above. PowerPoint paints a
 * pattern with them, not with fillColor/fillBackColor, as soon as either of
 * those is a scheme index (verified by patching the colours of one file).
 */
export function patternPaletteOf(media: PictureMedia): { fg: string; bg: string } | null {
  if (media.mediaType !== 'image/bmp' || media.bytes.length < 62) return null
  const bytes = media.bytes
  const entry = (at: number): string =>
    [bytes[at + 2]!, bytes[at + 1]!, bytes[at]!]
      .map((channel) => channel.toString(16).padStart(2, '0'))
      .join('')
      .toUpperCase()
  const first = entry(54)
  const second = entry(58)
  return isBlack(bytes, 58) ? { fg: first, bg: second } : { fg: second, bg: first }
}

const rotateRow = (row: number, by: number): number =>
  by === 0 ? row : ((row << by) | (row >> (8 - by))) & 0xff

function matchesShifted(mask: number[], preset: number[]): boolean {
  for (let dy = 0; dy < 8; dy++) {
    for (let dx = 0; dx < 8; dx++) {
      let same = true
      for (let y = 0; y < 8 && same; y++) {
        same = rotateRow(preset[(y + dy) % 8]!, dx) === mask[y]
      }
      if (same) return true
    }
  }
  return false
}

const popcount = (mask: number[]): number =>
  mask.reduce((sum, row) => {
    let bits = row
    while (bits) {
      sum += bits & 1
      bits >>= 1
    }
    return sum
  }, 0)

/** The preset a pattern cell is (up to the cell's phase), else the percentage preset of its density. */
export function patternPreset(mask: number[]): string {
  for (const [preset, rows] of Object.entries(PRESET_MASKS)) {
    if (matchesShifted(mask, rows)) return preset
  }
  const count = popcount(mask)
  let best = 'pct50'
  let bestDiff = Infinity
  for (const preset of PCT_PRESETS) {
    const diff = Math.abs(popcount(PRESET_MASKS[preset]!) - count)
    if (diff < bestDiff) {
      best = preset
      bestDiff = diff
    }
  }
  return best
}
