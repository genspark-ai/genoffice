/**
 * Shape animation (<p:timing>) read/write — the engine layer behind PowerPoint's
 * "Animations" tab.
 *
 * Model: a slide's animations are an ordered list SlideAnimation[], each item =
 * target shape (spid) + effect + trigger (onClick/withPrev/afterPrev) +
 * duration/delay. On write-back the whole <p:timing> is rebuilt (tmRoot → mainSeq
 * → one par per "click group" → one par per effect), structurally identical to
 * the skeleton PowerPoint itself generates, so the saved pptx plays directly in
 * PowerPoint.
 *
 * spid targeting: OOXML animations use <p:spTgt spid="N"/> pointing at the shape's
 * <p:cNvPr id="N">. The editor's element ids are transient (they change on
 * reparse), so elementSpid() extracts the stable cNvPr id from the element's raw
 * bytes for the mapping.
 *
 * Read-back: parsing our own generated skeleton round-trips losslessly; complex
 * timings generated by PowerPoint get a best-effort downgrade (unmodeled presetIDs
 * map to a similar effect in the same class).
 */
import type { Slide, SlideElement } from './types'

export type AnimEffectKind =
  // Entrance
  | 'appear'
  | 'fade'
  | 'flyIn'
  | 'wipe'
  | 'wipeDown'
  | 'splitIn'
  | 'bounce'
  | 'flipIn'
  | 'zoom'
  // Emphasis
  | 'pulse'
  | 'spin'
  | 'grow'
  | 'teeter'
  // Exit
  | 'disappear'
  | 'fadeOut'
  | 'flyOut'
  | 'wipeOut'
  | 'shrink'
  | 'zoomOut'
  // Motion path (move along a path)
  | 'motionPath'

export type AnimTrigger = 'onClick' | 'withPrev' | 'afterPrev'

export const ANIM_TRIGGERS: readonly AnimTrigger[] = ['onClick', 'withPrev', 'afterPrev']
export type AnimClass = 'entrance' | 'emphasis' | 'exit' | 'path'

export interface SlideAnimation {
  /** Target shape's cNvPr id (<p:spTgt spid>) */
  spid: number
  effect: AnimEffectKind
  trigger: AnimTrigger
  durationMs: number
  delayMs: number
  /**
   * Motion path (valid when effect='motionPath'): SVG subset M/L/C/Z,
   * coordinates 0..1 relative to slide width/height (same as OOXML animMotion's
   * relative path).
   */
  motionPath?: string
  /** Per-paragraph animation: 0-based paragraph number (written as pgRg st/end); unset = whole shape */
  paragraph?: number
}

/** Effect → class (entrance/emphasis/exit/motion path). */
export function animClassOf(effect: AnimEffectKind): AnimClass {
  switch (effect) {
    case 'appear':
    case 'fade':
    case 'flyIn':
    case 'wipe':
    case 'wipeDown':
    case 'splitIn':
    case 'bounce':
    case 'flipIn':
    case 'zoom':
      return 'entrance'
    case 'pulse':
    case 'spin':
    case 'grow':
    case 'teeter':
      return 'emphasis'
    case 'motionPath':
      return 'path'
    default:
      return 'exit'
  }
}

/** Extract the element's own <p:cNvPr id> from its raw bytes (the first one is the element itself; group children follow). */
export function elementSpid(el: SlideElement): number | null {
  const m = /<p:cNvPr\s[^>]*\bid="(\d+)"/.exec(el.anchor.originalXml)
  return m ? Number(m[1]) : null
}

