/** presetClass:presetID(:presetSubtype) → effect (read-back mapping; unmodeled ones map to a same-class approximation). */
export const ANIM_EFFECTS = Object.keys(PRESET) as readonly AnimEffectKind[]

function effectFromPreset(cls: string, id: number, sub: number): AnimEffectKind {
  if (cls === 'path') return 'motionPath'
  // Effects sharing a presetID distinguished by subtype (e.g. wipe direction)
  const bySub: Record<string, AnimEffectKind> = {
    'entr:22:1': 'wipe',
    'entr:22:4': 'wipeDown',
  }
  const exact: Record<string, AnimEffectKind> = {
    'entr:1': 'appear',
    'entr:10': 'fade',
    'entr:2': 'flyIn',
    'entr:22': 'wipe',
    'entr:16': 'splitIn',
    'entr:26': 'bounce',
    'entr:30': 'flipIn',
    'entr:23': 'zoom',
    'emph:26': 'pulse',
    'emph:8': 'spin',
    'emph:6': 'grow',
    'emph:32': 'teeter',
    'exit:1': 'disappear',
    'exit:10': 'fadeOut',
    'exit:2': 'flyOut',
    'exit:22': 'wipeOut',
    'exit:30': 'shrink',
    'exit:23': 'zoomOut',
  }
  const hit = bySub[`${cls}:${id}:${sub}`] ?? exact[`${cls}:${id}`]
  if (hit) return hit
  if (cls === 'exit') return 'fadeOut'
  if (cls === 'emph') return 'pulse'
  return 'fade'
}

const NODE_TYPE: Record<AnimTrigger, string> = {
  onClick: 'clickEffect',
  withPrev: 'withEffect',
  afterPrev: 'afterEffect',
}

interface IdGen {
  next: () => number
}

/**
 * Behavior target <p:tgtEl>. With paragraph, adds txEl/pgRg: ECMA-376
 * CT_IndexRange's st/end are 0-based paragraph indices (files generated by
 * PowerPoint use st="0" for the first paragraph), mapping directly.
 */
function tgtElXml(a: SlideAnimation): string {
  const inner =
    a.paragraph == null
      ? `<p:spTgt spid="${a.spid}"/>`
      : `<p:spTgt spid="${a.spid}"><p:txEl><p:pgRg st="${a.paragraph}" end="${a.paragraph}"/></p:txEl></p:spTgt>`
  return `<p:tgtEl>${inner}</p:tgtEl>`
}

/** Set style.visibility (entrance=visible / exit=hidden). delay is relative to the effect start. */
function setVisibilityXml(gen: IdGen, tgt: string, visible: boolean, delayMs: number): string {
  return (
    '<p:set><p:cBhvr>' +
    `<p:cTn id="${gen.next()}" dur="1" fill="hold"><p:stCondLst><p:cond delay="${delayMs}"/></p:stCondLst></p:cTn>` +
    tgt +
    '<p:attrNameLst><p:attrName>style.visibility</p:attrName></p:attrNameLst>' +
    `</p:cBhvr><p:to><p:strVal val="${visible ? 'visible' : 'hidden'}"/></p:to></p:set>`
  )
}

/** Attribute keyframe animation (tm is a per-mille time point 0..100000, val a formula string). */
function keyframeAnimXml(
  gen: IdGen,
  tgt: string,
  dur: number,
  attr: string,
  frames: Array<[tm: number, val: string]>,
): string {
  const tavs = frames
    .map(([tm, val]) => `<p:tav tm="${tm}"><p:val><p:strVal val="${val}"/></p:val></p:tav>`)
    .join('')
  return (
    '<p:anim calcmode="lin" valueType="num">' +
    `<p:cBhvr additive="base"><p:cTn id="${gen.next()}" dur="${dur}" fill="hold"/>` +
    tgt +
    `<p:attrNameLst><p:attrName>${attr}</p:attrName></p:attrNameLst></p:cBhvr>` +
    `<p:tavLst>${tavs}</p:tavLst></p:anim>`
  )
}

/** ppt_x/ppt_y translation animation (for fly in/out). */
function moveAnimXml(
  gen: IdGen,
  tgt: string,
  dur: number,
  attr: 'ppt_x' | 'ppt_y',
  from: string,
  to: string,
): string {
  return keyframeAnimXml(gen, tgt, dur, attr, [
    [0, from],
    [100000, to],
  ])
}

/** Default motionPath (straight line to the right, 1/4 of the slide width). */
export const DEFAULT_MOTION_PATH = 'M 0 0 L 0.25 0'

/** Move along a path (<p:animMotion>); the path gets the " E" end marker per OOXML convention. */
function motionAnimXml(gen: IdGen, tgt: string, dur: number, path: string): string {
  const p = path.trim() || DEFAULT_MOTION_PATH
  const pathAttr = /\bE$/.test(p) ? p : `${p} E`
  return (
    `<p:animMotion origin="layout" path="${pathAttr}" pathEditMode="relative">` +
    `<p:cBhvr><p:cTn id="${gen.next()}" dur="${dur}" fill="hold"/>` +
    tgt +
    '<p:attrNameLst><p:attrName>ppt_x</p:attrName><p:attrName>ppt_y</p:attrName></p:attrNameLst>' +
    '</p:cBhvr></p:animMotion>'
  )
}

/** Behavior list of one effect (a combination of set/animEffect/anim/animScale/animRot). */
function effectBehaviorsXml(gen: IdGen, a: SlideAnimation): string {
  const dur = Math.max(1, Math.round(a.durationMs))
  const target = tgtElXml(a)
  const show = setVisibilityXml(gen, target, true, 0)
  const hideAtEnd = setVisibilityXml(gen, target, false, Math.max(0, dur - 1))
  switch (a.effect) {
    case 'appear':
      return show
    case 'fade':
      return (
        show +
        `<p:animEffect transition="in" filter="fade"><p:cBhvr><p:cTn id="${gen.next()}" dur="${dur}"/>${target}</p:cBhvr></p:animEffect>`
      )
    case 'flyIn':
      return (
        show +
        moveAnimXml(gen, target, dur, 'ppt_x', '#ppt_x', '#ppt_x') +
        moveAnimXml(gen, target, dur, 'ppt_y', '1+#ppt_h/2', '#ppt_y')
      )
    case 'wipe':
      return (
        show +
        `<p:animEffect transition="in" filter="wipe(up)"><p:cBhvr><p:cTn id="${gen.next()}" dur="${dur}"/>${target}</p:cBhvr></p:animEffect>`
      )
    case 'wipeDown':
      return (
        show +
        `<p:animEffect transition="in" filter="wipe(down)"><p:cBhvr><p:cTn id="${gen.next()}" dur="${dur}"/>${target}</p:cBhvr></p:animEffect>`
      )
    case 'splitIn':
      return (
        show +
        `<p:animEffect transition="in" filter="split(inHorizontal)"><p:cBhvr><p:cTn id="${gen.next()}" dur="${dur}"/>${target}</p:cBhvr></p:animEffect>`
      )
    case 'bounce':
      // Drop from above + damped rebound (ppt_y keyframes approximating PowerPoint's bounce)
      return (
        show +
        keyframeAnimXml(gen, target, dur, 'ppt_y', [
          [0, '#ppt_y-0.25'],
          [55000, '#ppt_y'],
          [70000, '#ppt_y-0.08'],
          [85000, '#ppt_y'],
          [92000, '#ppt_y-0.03'],
          [100000, '#ppt_y'],
        ])
      )
    case 'flipIn':
      // Expand horizontally from 0 + fade in (approximation of Grow & Turn)
      return (
        show +
        `<p:animEffect transition="in" filter="fade"><p:cBhvr><p:cTn id="${gen.next()}" dur="${dur}"/>${target}</p:cBhvr></p:animEffect>` +
        `<p:animScale><p:cBhvr><p:cTn id="${gen.next()}" dur="${dur}" fill="hold"/>${target}</p:cBhvr>` +
        '<p:from x="0" y="100000"/><p:to x="100000" y="100000"/></p:animScale>'
      )
    case 'zoom':
      return (
        show +
        `<p:animScale><p:cBhvr><p:cTn id="${gen.next()}" dur="${dur}" fill="hold"/>${target}</p:cBhvr>` +
        '<p:from x="0" y="0"/><p:to x="100000" y="100000"/></p:animScale>'
      )
    case 'pulse':
      return (
        `<p:animScale><p:cBhvr><p:cTn id="${gen.next()}" dur="${Math.max(1, Math.round(dur / 2))}" autoRev="1" fill="hold"/>${target}</p:cBhvr>` +
        '<p:by x="106000" y="106000"/></p:animScale>'
      )
    case 'spin':
      return (
        `<p:animRot by="21600000"><p:cBhvr><p:cTn id="${gen.next()}" dur="${dur}" fill="hold"/>${target}` +
        '<p:attrNameLst><p:attrName>r</p:attrName></p:attrNameLst></p:cBhvr></p:animRot>'
      )
    case 'grow':
      return (
        `<p:animScale><p:cBhvr><p:cTn id="${gen.next()}" dur="${dur}" fill="hold"/>${target}</p:cBhvr>` +
        '<p:by x="150000" y="150000"/></p:animScale>'
      )
    case 'teeter':
      // Teeter: rock left/right around its own angle, then settle back
      return keyframeAnimXml(gen, target, dur, 'ppt_r', [
        [0, '#ppt_r'],
        [12500, '#ppt_r-9'],
        [37500, '#ppt_r+9'],
        [62500, '#ppt_r-6'],
        [87500, '#ppt_r+3'],
        [100000, '#ppt_r'],
      ])
    case 'disappear':
      return setVisibilityXml(gen, target, false, 0)
    case 'fadeOut':
      return (
        `<p:animEffect transition="out" filter="fade"><p:cBhvr><p:cTn id="${gen.next()}" dur="${dur}"/>${target}</p:cBhvr></p:animEffect>` +
        hideAtEnd
      )
    case 'flyOut':
      return (
        moveAnimXml(gen, target, dur, 'ppt_x', '#ppt_x', '#ppt_x') +
        moveAnimXml(gen, target, dur, 'ppt_y', '#ppt_y', '1+#ppt_h/2') +
        hideAtEnd
      )
    case 'wipeOut':
      return (
        `<p:animEffect transition="out" filter="wipe(down)"><p:cBhvr><p:cTn id="${gen.next()}" dur="${dur}"/>${target}</p:cBhvr></p:animEffect>` +
        hideAtEnd
      )
    case 'shrink':
      // Shrink and rotate out (approximation of Shrink & Turn)
      return (
        `<p:animScale><p:cBhvr><p:cTn id="${gen.next()}" dur="${dur}" fill="hold"/>${target}</p:cBhvr>` +
        '<p:from x="100000" y="100000"/><p:to x="1000" y="1000"/></p:animScale>' +
        `<p:animRot by="-5400000"><p:cBhvr><p:cTn id="${gen.next()}" dur="${dur}" fill="hold"/>${target}` +
        '<p:attrNameLst><p:attrName>r</p:attrName></p:attrNameLst></p:cBhvr></p:animRot>' +
        hideAtEnd
      )
    case 'zoomOut':
      return (
        `<p:animScale><p:cBhvr><p:cTn id="${gen.next()}" dur="${dur}" fill="hold"/>${target}</p:cBhvr>` +
        '<p:from x="100000" y="100000"/><p:to x="1000" y="1000"/></p:animScale>' +
        hideAtEnd
      )
    case 'motionPath':
      return motionAnimXml(gen, target, dur, a.motionPath ?? DEFAULT_MOTION_PATH)
  }
}

/**
 * Build the whole <p:timing>. Grouping rules (matching slideshow playback):
 * onClick starts a new "click group"; withPrev joins the current group (start =
 * previous effect's start + delay); afterPrev joins the current group (start =
 * previous effect's end + delay). If the first item is not onClick, group 0
 * plays automatically after the slide transition (stCondLst delay=0).
 */
interface Placed {
  a: SlideAnimation
  startMs: number
  grpId: number
}

/**
 * Grouping + absolute in-group start: onClick starts a new "click group"; withPrev
 * start = previous start + delay; afterPrev start = previous end + delay.
 * grpBase = animation count already used per spid (continued on incremental append).
 */
function placeAnims(
  anims: SlideAnimation[],
  grpBase?: Map<number, number>,
): Array<{ auto: boolean; items: Placed[] }> {
  const groups: Array<{ auto: boolean; items: Placed[] }> = []
  const grpCount = new Map<number, number>(grpBase ?? [])
  let prevStart = 0
  let prevEnd = 0
  for (const a of anims) {
    if (a.trigger === 'onClick' || groups.length === 0) {
      groups.push({ auto: a.trigger !== 'onClick', items: [] })
      prevStart = 0
      prevEnd = 0
    }
    const base = a.trigger === 'afterPrev' ? prevEnd : a.trigger === 'withPrev' ? prevStart : 0
    const start = base + Math.max(0, Math.round(a.delayMs))
    const grpId = grpCount.get(a.spid) ?? 0
    grpCount.set(a.spid, grpId + 1)
    groups[groups.length - 1]!.items.push({ a, startMs: start, grpId })
    prevStart = start
    prevEnd = start + Math.max(1, Math.round(a.durationMs))
  }
  return groups
}

/** One effect's <p:par> (cTn with presetID/presetClass + start + behaviors). */
function effectParXml(gen: IdGen, p: Placed): string {
  const preset = PRESET[p.a.effect]
  return (
    '<p:par>' +
    `<p:cTn id="${gen.next()}" presetID="${preset.id}" presetClass="${preset.cls}" presetSubtype="${preset.sub}" fill="hold" grpId="${p.grpId}" nodeType="${NODE_TYPE[p.a.trigger]}">` +
    `<p:stCondLst><p:cond delay="${p.startMs}"/></p:stCondLst>` +
    `<p:childTnLst>${effectBehaviorsXml(gen, p.a)}</p:childTnLst>` +
    '</p:cTn></p:par>'
  )
}

/** The two-level <p:par> wrapper of one "click group". */
function groupParXml(gen: IdGen, g: { auto: boolean; items: Placed[] }): string {
  const effects = g.items.map((p) => effectParXml(gen, p)).join('')
  return (
    '<p:par>' +
    `<p:cTn id="${gen.next()}" fill="hold">` +
    `<p:stCondLst><p:cond delay="${g.auto ? '0' : 'indefinite'}"/></p:stCondLst>` +
    '<p:childTnLst><p:par>' +
    `<p:cTn id="${gen.next()}" fill="hold"><p:stCondLst><p:cond delay="0"/></p:stCondLst>` +
    `<p:childTnLst>${effects}</p:childTnLst></p:cTn>` +
    '</p:par></p:childTnLst></p:cTn></p:par>'
  )
}

/**
 * bldP list for a full rebuild (shapes with paragraph animation get a single
 * summarizing build="p" bldP instead of one plain bldP per grpId).
 */
function bldPsXml(anims: SlideAnimation[]): string {
  const paraSpids = new Set(anims.filter((a) => a.paragraph != null).map((a) => a.spid))
  const bldSeen = new Set<string>()
  return anims
    .map((a, i) => {
      if (paraSpids.has(a.spid)) {
        const key = `p:${a.spid}`
        if (bldSeen.has(key)) return ''
        bldSeen.add(key)
        // grpId=0: on a full rebuild the spid's first animation always has grpId 0
        return `<p:bldP spid="${a.spid}" grpId="0" uiExpand="1" build="p"/>`
      }
      // grpId matches effect generation: the nth animation of the same spid has grpId=n
      const before = anims.slice(0, i).filter((x) => x.spid === a.spid).length
      const key = `${a.spid}:${before}`
      if (bldSeen.has(key)) return ''
      bldSeen.add(key)
      return `<p:bldP spid="${a.spid}" grpId="${before}"/>`
    })
    .join('')
}

export function buildTimingXml(anims: SlideAnimation[]): string {
  if (anims.length === 0) return ''
  let idCounter = 0
  const gen: IdGen = { next: () => ++idCounter }
  const rootId = gen.next() // 1 tmRoot
  const seqId = gen.next() // 2 mainSeq

  const groupXml = placeAnims(anims)
    .map((g) => groupParXml(gen, g))
    .join('')

  const bldPs = bldPsXml(anims)

  return (
    '<p:timing><p:tnLst><p:par>' +
    `<p:cTn id="${rootId}" dur="indefinite" restart="never" nodeType="tmRoot"><p:childTnLst>` +
    '<p:seq concurrent="1" nextAc="seek">' +
    `<p:cTn id="${seqId}" dur="indefinite" nodeType="mainSeq"><p:childTnLst>${groupXml}</p:childTnLst></p:cTn>` +
    '<p:prevCondLst><p:cond evt="onPrev" delay="0"><p:tgtEl><p:sldTgt/></p:tgtEl></p:cond></p:prevCondLst>' +
    '<p:nextCondLst><p:cond evt="onNext" delay="0"><p:tgtEl><p:sldTgt/></p:tgtEl></p:cond></p:nextCondLst>' +
    '</p:seq></p:childTnLst></p:cTn>' +
    '</p:par></p:tnLst>' +
    `<p:bldLst>${bldPs}</p:bldLst></p:timing>`
  )
}

const TIMING_RE = /<p:timing\b[^>]*\/>|<p:timing\b[^>]*>[\s\S]*?<\/p:timing>/

/** Content span of the mainSeq cTn; returns null when there is no main sequence. */
function mainSeqSpan(timing: string): { start: number; end: number } | null {
  const m = /<p:cTn\b[^>]*\bnodeType="mainSeq"[^>]*>/.exec(timing)
  if (!m) return null
  const start = m.index + m[0].length
  return { start, end: findCTnEnd(timing, start) }
}

/** Whether the tmRoot cTn's childTnLst has no children left (after removing the main sequence, decides whether the whole timing is still meaningful). */
function rootChildTnLstEmpty(timing: string): boolean {
  const rootM = /<p:cTn\b[^>]*\bnodeType="tmRoot"[^>]*>/.exec(timing)
  if (!rootM) return true
  const childOpen = timing.indexOf('<p:childTnLst>', rootM.index + rootM[0].length)
  if (childOpen < 0) return true
  const childClose = findBalancedClose(timing, childOpen, 'p:childTnLst')
  if (childClose < 0) return true
  return !timing.slice(childOpen + '<p:childTnLst>'.length, childClose).trim()
}

/** Strip all <p:bldP> from bldLst and write ours; bldDgm/bldOleChart/bldGraphic etc. are kept. */
function rebuildBldLst(timing: string, anims: SlideAnimation[]): string {
  const ours = bldPsXml(anims)
  const bldOpen = /<p:bldLst\b[^>]*>/.exec(timing)
  if (!bldOpen) {
    if (!ours) return timing
    const tEnd = timing.lastIndexOf('</p:timing>')
    if (tEnd < 0) return timing
    return timing.slice(0, tEnd) + `<p:bldLst>${ours}</p:bldLst>` + timing.slice(tEnd)
  }
  const close = findBalancedClose(timing, bldOpen.index, 'p:bldLst')
  if (close < 0) return timing
  const inner = timing.slice(bldOpen.index + bldOpen[0].length, close)
  const kept = inner.replace(/<p:bldP\b[^>]*\/>|<p:bldP\b[^>]*>[\s\S]*?<\/p:bldP>/g, '')
  const newInner = ours + kept
  const replacement = newInner ? `<p:bldLst>${newInner}</p:bldLst>` : ''
  return timing.slice(0, bldOpen.index) + replacement + timing.slice(close + '</p:bldLst>'.length)
}

/**
 * Overwrite-style rebuild that only touches the main sequence: the mainSeq childTnLst
 * is replaced with new effect groups; unmodeled siblings (interactiveSeq, media
 * timelines, ...) keep their original bytes; bldP is rewritten, other bld* kept.
 * Empty anims removes the whole <p:seq> (main sequence); if the root childTnLst becomes
 * empty as a result, returns '' (delete the timing).
 * Returns null when the structure is unexpected; the caller falls back to a fresh build.
 */
function rebuildTimingPreservingXml(timing: string, anims: SlideAnimation[]): string | null {
  const seqCtnM = /<p:cTn\b[^>]*\bnodeType="mainSeq"[^>]*>/.exec(timing)
  let newTiming: string
  if (anims.length === 0) {
    if (!seqCtnM) return rebuildBldLst(timing, anims)
    const seqStart = timing.lastIndexOf('<p:seq', seqCtnM.index)
    if (seqStart < 0) return null
    const seqClose = findBalancedClose(timing, seqStart, 'p:seq')
    if (seqClose < 0) return null
    newTiming = timing.slice(0, seqStart) + timing.slice(seqClose + '</p:seq>'.length)
    newTiming = rebuildBldLst(newTiming, anims)
    return rootChildTnLstEmpty(newTiming) ? '' : newTiming
  }

  const gen = makeGenAfterMaxId(timing)
  const groupXml = placeAnims(anims)
    .map((g) => groupParXml(gen, g))
    .join('')
  if (seqCtnM) {
    const childOpen = timing.indexOf('<p:childTnLst>', seqCtnM.index + seqCtnM[0].length)
    if (childOpen < 0) return null
    const childClose = findBalancedClose(timing, childOpen, 'p:childTnLst')
    if (childClose < 0) return null
    newTiming =
      timing.slice(0, childOpen + '<p:childTnLst>'.length) + groupXml + timing.slice(childClose)
  } else {
    // Original timing has no main sequence (only trigger/media nodes): insert a brand-new <p:seq> at the end of the tmRoot childTnLst
    const rootM = /<p:cTn\b[^>]*\bnodeType="tmRoot"[^>]*>/.exec(timing)
    if (!rootM) return null
    const childOpen = timing.indexOf('<p:childTnLst>', rootM.index + rootM[0].length)
    if (childOpen < 0) return null
    const childClose = findBalancedClose(timing, childOpen, 'p:childTnLst')
    if (childClose < 0) return null
    const seqXml =
      '<p:seq concurrent="1" nextAc="seek">' +
      `<p:cTn id="${gen.next()}" dur="indefinite" nodeType="mainSeq"><p:childTnLst>${groupXml}</p:childTnLst></p:cTn>` +
      '<p:prevCondLst><p:cond evt="onPrev" delay="0"><p:tgtEl><p:sldTgt/></p:tgtEl></p:cond></p:prevCondLst>' +
      '<p:nextCondLst><p:cond evt="onNext" delay="0"><p:tgtEl><p:sldTgt/></p:tgtEl></p:cond></p:nextCondLst>' +
      '</p:seq>'
    newTiming = timing.slice(0, childClose) + seqXml + timing.slice(childClose)
  }
  return rebuildBldLst(newTiming, anims)
}

/**
 * In-place patch of the bodySuffix's <p:timing> (schema order: after transition, before extLst).
 * With an existing timing, only the main sequence is rebuilt and unmodeled sibling
 * nodes are kept; empty anims removes the main sequence (the timing stays if other
 * nodes remain, and is removed only when fully empty). Returns the new bodySuffix.
 */
export function patchSlideTimingXml(bodySuffix: string, anims: SlideAnimation[]): string {
  const timingM = TIMING_RE.exec(bodySuffix)
  if (timingM) {
    const rebuilt = rebuildTimingPreservingXml(timingM[0], anims)
    if (rebuilt != null)
      return (
        bodySuffix.slice(0, timingM.index) +
        rebuilt +
        bodySuffix.slice(timingM.index + timingM[0].length)
      )
  }
  const stripped = bodySuffix.replace(TIMING_RE, '')
  if (anims.length === 0) return stripped
  const xml = buildTimingXml(anims)
  // Insertion point: before </p:sld>; with a slide-level <p:extLst> (legal after
  // timing, but PowerPoint emits timing first), insert before the last extLst
  const ext = stripped.lastIndexOf('<p:extLst')
  const sldEnd = stripped.lastIndexOf('</p:sld>')
  const at = ext >= 0 ? ext : sldEnd
  if (at < 0) return stripped
  return stripped.slice(0, at) + xml + stripped.slice(at)
}

// ── Read: <p:timing> → SlideAnimation[] ────────────────────────────────

/** Balanced scan: from openEnd (end of the open tag) find the matching </p:cTn>, returning the content end. */
function findCTnEnd(xml: string, openEnd: number): number {
  const re = /<p:cTn\b[^>]*?(\/?)>|<\/p:cTn>/g
  re.lastIndex = openEnd
  let depth = 1
  let m: RegExpExecArray | null
  while ((m = re.exec(xml)) !== null) {
    if (m[0] === '</p:cTn>') {
      depth--
      if (depth === 0) return m.index
    } else if (m[1] !== '/') {
      depth++
    }
  }
  return xml.length
}

/**
 * Read the bodySuffix's animation list (for UI echo + slideshow).
 * Parses every effect cTn carrying presetClass; delay is derived back to the user
 * delay per the write convention (withPrev minus previous start / afterPrev minus
 * previous end).
 */
export function readSlideTimingXml(bodySuffix: string): SlideAnimation[] {
  const timing = TIMING_RE.exec(bodySuffix)?.[0]
  if (!timing) return []
  // Read only the main sequence: interactiveSeq trigger animations etc. are not modeled, avoiding mistakenly absorbing them as click animations on rewrite
  const seq = mainSeqSpan(timing)
  if (!seq) return []
  const out: SlideAnimation[] = []
  const re = /<p:cTn\b([^>]*\bpresetClass="[^"]*"[^>]*)>/g
  re.lastIndex = seq.start
  let m: RegExpExecArray | null
  let prevStart = 0
  let prevEnd = 0
  while ((m = re.exec(timing)) !== null && m.index < seq.end) {
    const attrs = m[1]!
    const cls = /\bpresetClass="([^"]*)"/.exec(attrs)?.[1] ?? 'entr'
    const pid = Number(/\bpresetID="(\d+)"/.exec(attrs)?.[1] ?? '0')
    const psub = Number(/\bpresetSubtype="(\d+)"/.exec(attrs)?.[1] ?? '0')
    const nodeType = /\bnodeType="([^"]*)"/.exec(attrs)?.[1] ?? 'clickEffect'
    const trigger: AnimTrigger =
      nodeType === 'withEffect' ? 'withPrev' : nodeType === 'afterEffect' ? 'afterPrev' : 'onClick'
    const bodyEnd = findCTnEnd(timing, re.lastIndex)
    const body = timing.slice(re.lastIndex, bodyEnd)
    re.lastIndex = bodyEnd

    const spidM = /<p:spTgt\s[^>]*\bspid="(\d+)"/.exec(body)
    if (!spidM) continue
    const spid = Number(spidM[1])
    // Start: the effect cTn's own stCondLst (first cond delay at the body start)
    const startMs = Number(/^\s*<p:stCondLst><p:cond delay="(\d+)"/.exec(body)?.[1] ?? '0')
    // Duration: the largest numeric dur among the behaviors
    let durationMs = 0
    const durRe = /\bdur="(\d+)"/g
    let dm: RegExpExecArray | null
    while ((dm = durRe.exec(body)) !== null) durationMs = Math.max(durationMs, Number(dm[1]))
    // pulse with autoRev: actual duration = dur*2
    if (/\bautoRev="1"/.test(body)) durationMs *= 2
    const effect = effectFromPreset(cls, pid, psub)
    if (effect === 'appear' || effect === 'disappear') durationMs = 0

    if (trigger === 'onClick') {
      prevStart = 0
      prevEnd = 0
    }
    const base = trigger === 'afterPrev' ? prevEnd : trigger === 'withPrev' ? prevStart : 0
    const delayMs = Math.max(0, startMs - base)
    prevStart = startMs
    prevEnd = startMs + Math.max(1, durationMs)

    const anim: SlideAnimation = { spid, effect, trigger, durationMs, delayMs }
    const pgM = /<p:pgRg\s[^>]*\bst="(\d+)"/.exec(body)
    if (pgM) anim.paragraph = Number(pgM[1])
    if (effect === 'motionPath') {
      // Path read-back: drop the " E" end marker added on write, restoring the user path
      const path = /<p:animMotion\b[^>]*\bpath="([^"]*)"/.exec(body)?.[1]
      anim.motionPath = (path ?? DEFAULT_MOTION_PATH).replace(/\s*E$/, '').trim()
    }
    out.push(anim)
  }
  return out
}

// ── Incremental write-back (keeps unmodeled timing nodes) ──────────────

function animEq(x: SlideAnimation, y: SlideAnimation): boolean {
  return (
    x.spid === y.spid &&
    x.effect === y.effect &&
    x.trigger === y.trigger &&
    x.durationMs === y.durationMs &&
    x.delayMs === y.delayMs &&
    (x.motionPath ?? null) === (y.motionPath ?? null) &&
    (x.paragraph ?? null) === (y.paragraph ?? null)
  )
}

/** Balanced scan for the matching close tag: openStart points at the '<' of <tag …>; returns the start of </tag>, or -1 if not found. */
function findBalancedClose(xml: string, openStart: number, tag: string): number {
  const re = new RegExp(`<${tag}\\b[^>]*?(/?)>|</${tag}>`, 'g')
  re.lastIndex = openStart
  let depth = 0
  let m: RegExpExecArray | null
  while ((m = re.exec(xml)) !== null) {
    if (m[0].startsWith(`</`)) {
      depth--
      if (depth === 0) return m.index
    } else if (m[1] !== '/') {
      depth++
    }
  }
  return -1
}

/** Span in the timing of the nth effect <p:par> (cTn with presetClass inside the main sequence); order matches readSlideTimingXml. */
function nthEffectParSpan(timing: string, n: number): { start: number; end: number } | null {
  const seq = mainSeqSpan(timing)
  if (!seq) return null
  const re = /<p:cTn\b[^>]*\bpresetClass="[^"]*"[^>]*>/g
  re.lastIndex = seq.start
  let m: RegExpExecArray | null
  let i = 0
  while ((m = re.exec(timing)) !== null && m.index < seq.end) {
    if (i++ < n) {
      re.lastIndex = findCTnEnd(timing, re.lastIndex)
      continue
    }
    const parStart = timing.lastIndexOf('<p:par', m.index)
    if (parStart < 0) return null
    const closeAt = findBalancedClose(timing, parStart, 'p:par')
    if (closeAt < 0) return null
    return { start: parStart, end: closeAt + '</p:par>'.length }
  }
  return null
}

/** Replay the grouping semantics to compute each animation's absolute in-group start (same as placeAnims). */
function absStarts(anims: SlideAnimation[]): number[] {
  const out: number[] = []
  let prevStart = 0
  let prevEnd = 0
  for (const a of anims) {
    if (a.trigger === 'onClick') {
      prevStart = 0
      prevEnd = 0
    }
    const base = a.trigger === 'afterPrev' ? prevEnd : a.trigger === 'withPrev' ? prevStart : 0
    const start = base + Math.max(0, Math.round(a.delayMs))
    out.push(start)
    prevStart = start
    prevEnd = start + Math.max(1, Math.round(a.durationMs))
  }
  return out
}

/** Largest numeric id already in the timing; incrementally generated cTn ids continue after it (unique within the slide). */
function makeGenAfterMaxId(timing: string): IdGen {
  let maxId = 0
  for (const m of timing.matchAll(/\bid="(\d+)"/g)) maxId = Math.max(maxId, Number(m[1]))
  let c = maxId
  return { next: () => ++c }
}

/** Append bldP into <p:bldLst> (created before </p:timing> if missing). Existing (spid,grpId) pairs are skipped. */
function appendBldPs(timing: string, items: Placed[]): string {
  const seen = new Set<string>()
  for (const m of timing.matchAll(/<p:bldP\b[^>]*\bspid="(\d+)"[^>]*\bgrpId="(\d+)"/g)) {
    seen.add(`${m[1]}:${m[2]}`)
  }
  // spids already having build="p": write only one paragraph bldP per shape
  const paraSeen = new Set<string>()
  for (const m of timing.matchAll(/<p:bldP\b[^>]*\bspid="(\d+)"[^>]*\bbuild="p"/g))
    paraSeen.add(m[1]!)
  const parts: string[] = []
  for (const p of items) {
    if (p.a.paragraph != null) {
      const k = String(p.a.spid)
      if (paraSeen.has(k)) continue
      paraSeen.add(k)
      parts.push(`<p:bldP spid="${p.a.spid}" grpId="${p.grpId}" uiExpand="1" build="p"/>`)
    } else {
      const k = `${p.a.spid}:${p.grpId}`
      if (seen.has(k)) continue
      seen.add(k)
      parts.push(`<p:bldP spid="${p.a.spid}" grpId="${p.grpId}"/>`)
    }
  }
  const add = parts.join('')
  if (!add) return timing
  const bldEnd = timing.lastIndexOf('</p:bldLst>')
  if (bldEnd >= 0) return timing.slice(0, bldEnd) + add + timing.slice(bldEnd)
  const tEnd = timing.lastIndexOf('</p:timing>')
  if (tEnd < 0) return timing
  return timing.slice(0, tEnd) + `<p:bldLst>${add}</p:bldLst>` + timing.slice(tEnd)
}

/**
 * Incremental <p:timing> patch: touches only the affected effect nodes; unmodeled
 * sibling nodes (interactive trigger sequences, text-level animations, media
 * timelines, ...) keep their original bytes. Two supported shapes:
 *   A. Pure append (old list is a prefix of the new one, and the first added item
 *      is onClick) → new click groups are inserted at the end of the mainSeq;
 *   B. Tail single-item edit (same length, only one item changed, trigger/target
 *      unchanged, and no chained dependency after it) → replace that effect's
 *      <p:par> wholesale.
 * Everything else (delete/reorder/trigger change) returns null and the caller
 * falls back to a full rebuild.
 */
export function patchSlideTimingIncrementalXml(
  bodySuffix: string,
  anims: SlideAnimation[],
): string | null {
  const timingM = TIMING_RE.exec(bodySuffix)
  if (!timingM) return null
  const timing = timingM[0]
  const old = readSlideTimingXml(bodySuffix)
  if (!old.length || !anims.length) return null
  const splice = (newTiming: string) =>
    bodySuffix.slice(0, timingM.index) + newTiming + bodySuffix.slice(timingM.index + timing.length)

  // A. Pure append
  if (anims.length > old.length && old.every((o, i) => animEq(o, anims[i]!))) {
    const added = anims.slice(old.length)
    if (added[0]!.trigger !== 'onClick') return null
    // Mixing whole-shape and paragraph animations on one shape changes the bldP form
    // (plain ↔ build="p"); defer to a full rebuild
    const kindBySpid = new Map<number, number>()
    for (const a of anims)
      kindBySpid.set(a.spid, (kindBySpid.get(a.spid) ?? 0) | (a.paragraph == null ? 1 : 2))
    if (added.some((a) => kindBySpid.get(a.spid) === 3)) return null
    const seqM = /<p:cTn\b[^>]*\bnodeType="mainSeq"[^>]*>/.exec(timing)
    if (!seqM) return null
    const childOpen = timing.indexOf('<p:childTnLst>', seqM.index + seqM[0].length)
    if (childOpen < 0) return null
    const childClose = findBalancedClose(timing, childOpen, 'p:childTnLst')
    if (childClose < 0) return null

    const gen = makeGenAfterMaxId(timing)
    const grpBase = new Map<number, number>()
    for (const a of old) grpBase.set(a.spid, (grpBase.get(a.spid) ?? 0) + 1)
    const groups = placeAnims(added, grpBase)
    const groupsXml = groups.map((g) => groupParXml(gen, g)).join('')
    let newTiming = timing.slice(0, childClose) + groupsXml + timing.slice(childClose)
    newTiming = appendBldPs(
      newTiming,
      groups.flatMap((g) => g.items),
    )
    return splice(newTiming)
  }

  // B. Tail single-item edit
  if (anims.length === old.length) {
    const diffIdx = anims.flatMap((a, i) => (animEq(a, old[i]!) ? [] : [i]))
    if (diffIdx.length !== 1) return null
    const i = diffIdx[0]!
    const o = old[i]!
    const a = anims[i]!
    // Trigger/target unchanged (a paragraph change affects the bldP form); no later withPrev/afterPrev chain depends on this item's start/end
    if (o.trigger !== a.trigger || o.spid !== a.spid) return null
    if ((o.paragraph ?? null) !== (a.paragraph ?? null)) return null
    const next = anims[i + 1]
    if (next && next.trigger !== 'onClick') return null
    const span = nthEffectParSpan(timing, i)
    if (!span) return null
    const gen = makeGenAfterMaxId(timing)
    // Keep the original cTn's grpId (bldP is keyed on it); recompute from the list only when missing
    const origGrpId = /\bgrpId="(\d+)"/.exec(timing.slice(span.start, span.end))?.[1]
    const grpId =
      origGrpId != null
        ? Number(origGrpId)
        : anims.slice(0, i).filter((x) => x.spid === a.spid).length
    const par = effectParXml(gen, { a, startMs: absStarts(anims)[i]!, grpId })
    return splice(timing.slice(0, span.start) + par + timing.slice(span.end))
  }

  return null
}

/**
 * Set the slide's full animation list. Tries the incremental patch first (append /
 * tail single-item edit, keeping unmodeled timing nodes); when inapplicable, falls
 * back to the overwrite-style full rebuild (writes bodySuffix, persisted with the
 * whole-slide rebuild on save).
 */
export function setSlideAnimations(slide: Slide, anims: SlideAnimation[]): void {
  slide.bodySuffix =
    patchSlideTimingIncrementalXml(slide.bodySuffix, anims) ??
    patchSlideTimingXml(slide.bodySuffix, anims)
  slide.structureDirty = true
}

/** Read the current slide's animation list. */
export function getSlideAnimations(slide: Slide): SlideAnimation[] {
  return readSlideTimingXml(slide.bodySuffix)
}

/** Innermost balanced <tag>…</tag> span containing the given index. */
function enclosingTagSpan(
  xml: string,
  at: number,
  tag: string,
): { start: number; end: number } | null {
  const re = new RegExp(`<${tag}\\b[^>]*>|</${tag}>`, 'g')
  const stack: number[] = []
  let m: RegExpExecArray | null
  while ((m = re.exec(xml)) !== null) {
    if (m[0][1] !== '/') {
      if (!m[0].endsWith('/>')) stack.push(m.index)
    } else {
      const start = stack.pop()
      if (start === undefined) return null
      if (start <= at && at < re.lastIndex) return { start, end: re.lastIndex }
    }
  }
  return null
}

/** Nearest preceding open <tag> that is still open at `at` (self-closing and
    already-closed occurrences skipped; these tags do not self-nest). */
function wrappedBy(xml: string, at: number, tag: string): boolean {
  let from = at
  for (;;) {
    const open = xml.lastIndexOf(`<${tag}`, from)
    if (open < 0) return false
    const gt = xml.indexOf('>', open)
    if (gt < 0) return false
    if (xml[gt - 1] === '/') {
      from = open - 1
      continue
    }
    return xml.indexOf(`</${tag}>`, gt) > at
  }
}

/** Whether the spTgt at `at` is a trigger reference (wrapped by an open
    <p:cond>) rather than an effect/media target — an effect block's own
    already-closed delay cond (<p:cond delay="0"/> inside its cTn) must not
    count as a wrapper. */
function isTriggerRef(xml: string, at: number): boolean {
  return wrappedBy(xml, at, 'p:cond')
}

/**
 * Remove the effect blocks targeting the given cNvPr ids from the slide's
 * <p:timing>. Element removal must go through this or the timing keeps
 * dangling <p:spTgt spid> refs (PowerPoint flags the file). Byte surgery —
 * unmodeled effect parameters elsewhere survive (no rebuild):
 * - a trigger reference (<p:cond><p:tgtEl>) takes its whole interactiveSeq
 *   with it (the animations only ever ran off the removed trigger shape);
 * - an effect/media target removes the narrowest wrapper (video/audio/par)
 *   that does not contain surviving shapes' targets — when no such wrapper
 *   exists the ref is left in place rather than destroying other animations;
 * - matching <p:bldP> build refs go too; a timing left with no targets and
 *   no diagram builds is dropped entirely.
 */
export function pruneTimingForSpids(slide: Slide, spids: ReadonlySet<number>): boolean {
  if (!spids.size) return false
  const timing = /<p:timing>[\s\S]*?<\/p:timing>/.exec(slide.bodySuffix)?.[0]
  if (!timing) return false
  let xml = timing
  let changed = false
  for (;;) {
    const hits = [...xml.matchAll(/<p:spTgt spid="(\d+)"/g)].filter((x) => spids.has(Number(x[1])))
    let removed = false
    for (const hit of hits) {
      const at = hit.index
      let span: { start: number; end: number } | null = null
      if (isTriggerRef(xml, at)) {
        const seq = enclosingTagSpan(xml, at, 'p:seq')
        if (seq) {
          const head = xml.slice(seq.start, seq.start + 400)
          if (head.includes('nodeType="interactiveSeq"')) span = seq
        }
      }
      if (!span) {
        const candidates = ['p:video', 'p:audio', 'p:par']
          .map((t) => enclosingTagSpan(xml, at, t))
          .filter((sp): sp is { start: number; end: number } => sp !== null)
          .sort((a, b) => a.end - a.start - (b.end - b.start))
        span =
          candidates.find(
            (sp) =>
              ![...xml.slice(sp.start, sp.end).matchAll(/<p:spTgt spid="(\d+)"/g)].some(
                (m) => !spids.has(Number(m[1])),
              ),
          ) ?? null
      }
      if (!span) continue
      xml = xml.slice(0, span.start) + xml.slice(span.end)
      changed = true
      removed = true
      break
    }
    if (!removed) break
  }
  for (const id of spids) {
    const re = new RegExp(
      `<p:bldP spid="${id}"[^>]*/>|<p:bldP spid="${id}"[^>]*>[\\s\\S]*?</p:bldP>`,
      'g',
    )
    if (re.test(xml)) {
      xml = xml.replace(re, '')
      changed = true
    }
  }
  if (!changed) return false
  xml = xml.replace(/<p:bldLst\s*\/>|<p:bldLst\s*>\s*<\/p:bldLst>/g, '')
  if (/<p:spTgt\b/.test(xml)) {
    // Collapse innermost pars that lost every target, then their emptied ancestors
    let prev: string
    do {
      prev = xml
      xml = xml.replace(/<p:par\b[^>]*>(?:(?!<p:par\b|<\/p:par>)[\s\S])*?<\/p:par>/g, (blk) =>
        /<p:spTgt\b/.test(blk) ? blk : '',
      )
    } while (xml !== prev)
  }
  slide.bodySuffix =
    /<p:spTgt\b/.test(xml) || /<p:bldDgm\b/.test(xml)
      ? slide.bodySuffix.replace(timing, xml)
      : slide.bodySuffix.replace(timing, '')
  slide.structureDirty = true
  return true
}

/** Every cNvPr id inside an element's XML fragment (group children included). */
export function cNvPrIdsInXml(xml: string): Set<number> {
  const out = new Set<number>()
  for (const m of xml.matchAll(/<p:cNvPr\b[^>]*?\bid="(\d+)"/g)) out.add(Number(m[1]))
  return out
}
