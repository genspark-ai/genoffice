/** 8×8 boolean grid for a preset (true = foreground pixel); pct50 fallback. */
export function patternGrid(preset: string): boolean[][] {
  const pct = PCT[preset]
  if (pct != null) {
    const th = (pct / 100) * 64
    return BAYER8.map((row) => row.map((v) => v < th))
  }
  const mask = MASKS[preset] ?? MASKS['cross']!
  return mask.map((row) => Array.from({ length: 8 }, (_, u) => !!(row & (1 << (7 - u)))))
}
