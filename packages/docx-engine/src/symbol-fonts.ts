const SYMBOL_FONT_MAPS: Record<string, Record<number, string>> = {
  symbol: SYMBOL,
  wingdings: WINGDINGS,
  'wingdings 2': WINGDINGS_2,
  'wingdings 3': WINGDINGS_3,
  webdings: WEBDINGS,
}

export function isSymbolFont(font: string | null | undefined): boolean {
  return !!font && font.trim().toLowerCase() in SYMBOL_FONT_MAPS
}

/** glyph code (raw byte or its U+F0xx private-use form) → Unicode equivalent, null when unknown */
export function decodeSymbolChar(font: string, code: number): string | null {
  const map = SYMBOL_FONT_MAPS[font.trim().toLowerCase()]
  if (!map) return null
  const low = code >= 0xf000 && code <= 0xf0ff ? code - 0xf000 : code
  if (low === 0x20) return ' '
  return map[low] ?? null
}

/** stand-ins text fonts draw as monochrome glyphs; pictographs and emoji-presentation
 *  characters would swap the symbol font's own drawing for a colour emoji */
const TEXT_GLYPH_RE = /^[^\p{Emoji_Presentation}\u{10000}-\u{10FFFF}]$/u

/** the U+F0xx private-use form of a w:sym hex char (how symbol-font cmaps index glyphs); null = bad char */
export function symbolPuaChar(charHex: string): string | null {
  const code = parseInt(charHex, 16)
  return Number.isFinite(code) ? String.fromCodePoint((code & 0xff) + 0xf000) : null
}

/** display glyph of a w:sym (font + hex char): the Unicode equivalent when the
 *  font is a known symbol face, else the U+F0xx private-use form; null = bad char */
export function symbolGlyph(font: string, charHex: string): string | null {
  const code = parseInt(charHex, 16)
  if (!Number.isFinite(code)) return null
  return decodeSymbolChar(font, code) ?? symbolPuaChar(charHex)
}

/** raw-byte glyph codes → their U+F0xx private-use form (how symbol-font cmaps index glyphs) */
export function toSymbolPua(text: string): string {
  let out = ''
  for (const ch of text) {
    const code = ch.codePointAt(0) as number
    out += code > 0x20 && code <= 0xff ? String.fromCodePoint(0xf000 + code) : ch
  }
  return out
}

/** whole string decode; null unless every non-whitespace char maps. `textGlyphsOnly`
 *  (text runs, which keep their font otherwise) also refuses pictograph stand-ins and
 *  ASCII approximations (Webdings 0x3E -> A), so the font is only dropped for glyphs a
 *  text font draws faithfully */
export function decodeSymbolText(
  font: string,
  text: string,
  opts?: { textGlyphsOnly?: boolean },
): string | null {
  if (!isSymbolFont(font)) return null
  let out = ''
  for (const ch of text) {
    const code = ch.codePointAt(0) as number
    if (code <= 0x20 || code === 0xa0) {
      out += ch
      continue
    }
    const mapped = decodeSymbolChar(font, code)
    if (mapped === null) return null
    if (opts?.textGlyphsOnly) {
      const ascii = (mapped.codePointAt(0) as number) < 0x80
      if (!TEXT_GLYPH_RE.test(mapped) || (ascii && mapped !== String.fromCharCode(code & 0xff)))
        return null
    }
    out += mapped
  }
  return out
}
